import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {parseMapData} from '../js/hy/map-source.js';
import {Polygon} from '../js/hy/tiling.js';

// Source ownership, including the two TT rewards outside the contiguous TT area.
export const isTypeMapLine = line => line === 409 || (line >= 802 && line <= 1702) || (line >= 1726 && line <= 1727);

export function assertTypeMapAnchors(source) {
    const lines = source.split('\n').map(line => line.trim());
    const expect = (line, condition, label) => {
        if (!condition(lines[line - 1] ?? '')) throw Error(`Built-in TT ownership anchor moved: ${label} at line ${line}; review the partition boundaries`);
    };
    expect(409, line => line.startsWith(':%*,5$[[type]]'), '[[type]]');
    expect(801, line => line.startsWith(':port-iff,5@'), 'main-world hint before TT');
    expect(802, line => line.startsWith(':type,4@'), ':type,4');
    expect(1702, line => line === ':%,3$[=getD:666]', 'last TT reward');
    expect(1704, line => line === '// 序数附加', 'ordinal additions');
    const previousRecord = lines.slice(0, 1703).findLastIndex(line => line && !line.startsWith('//'));
    if (previousRecord !== 1701) throw Error('Unexpected TT record before ordinal additions');
    expect(1726, line => /^\d[\d,]*\$\[\[ttord\]\]/.test(line), '[[ttord]]');
    expect(1727, line => line.startsWith(':ttord,1,3@'), 'ttord hint');
}

export function buildBuiltinMap(source) {
    const declaration = 'export const mapData =';
    if (!source.startsWith(declaration)) throw Error('Expected the original mapData authoring module');
    assertTypeMapAnchors(source);
    const mapData = new Function(source.replace(declaration, 'const mapData =') + '\nreturn mapData;')();
    const {tiles, names, lines} = parseMapData(mapData, new Polygon(6, 4));
    const main = {tiles: [], names: []}, type = {tiles: [], names: []};
    const owners = new Map();
    let order = 0;
    for (const [hash, tile] of tiles) {
        const line = lines.get(hash);
        if (line === undefined) throw Error(`Missing source line for ${hash}`);
        const owner = isTypeMapLine(line) ? type : main;
        owners.set(hash, owner);
        owner.tiles.push([order++, hash, tile]);
    }
    order = 0;
    for (const [name, hash] of names) {
        const owner = owners.get(hash);
        if (!owner) throw Error(`Missing final tile for name ${name}`);
        owner.names.push([order++, name, hash]);
    }
    return {main, type};
}

// JSON alone drops present-but-undefined names on unnamed non-chain tiles.
function literal(value) {
    if (value === undefined) return 'undefined';
    if (value === null) return 'null';
    if (typeof value === 'string') return JSON.stringify(value).replaceAll('\u2028', '\\u2028').replaceAll('\u2029', '\\u2029');
    if (typeof value === 'boolean') return String(value);
    if (typeof value === 'number' && Number.isFinite(value)) return Object.is(value, -0) ? '-0' : String(value);
    if (Array.isArray(value)) return `[${value.map(literal).join(',')}]`;
    if (typeof value === 'object') return `{${Object.keys(value).map(key => `${key === '__proto__' ? '["__proto__"]' : JSON.stringify(key)}:${literal(value[key])}`).join(',')}}`;
    throw Error(`Unsupported map literal: ${typeof value}`);
}

export function renderBuiltinMap(data, name, importPath, sourceHash) {
    return `// Generated by tools/build-builtin-map.mjs. Edit src/hy/map.ts, then regenerate.\n` +
        `// Authoring source SHA256: ${sourceHash}\n` +
        `import type { BuiltinMapData } from ${JSON.stringify(importPath)};\n\n` +
        `export const ${name}: BuiltinMapData = {\n` +
        `    tiles: [\n${data.tiles.map(row => `        ${literal(row)},`).join('\n')}\n    ],\n` +
        `    names: [\n${data.names.map(row => `        ${literal(row)},`).join('\n')}\n    ]\n};\n`;
}

export async function generateBuiltinMaps({check = false} = {}) {
    const source = await readFile(new URL('../src/hy/map.ts', import.meta.url), 'utf8');
    const sourceHash = createHash('sha256').update(source.replaceAll('\r\n', '\n')).digest('hex');
    console.log('Parsing original authoring DSL and checking TT ownership anchors...');
    const {main, type} = buildBuiltinMap(source);
    const targets = [
        ['../src/hy/builtin/main-map.ts', renderBuiltinMap(main, 'mainMapModData', '../builtin-map.js', sourceHash)],
        ['../src/hy/type-map.ts', renderBuiltinMap(type, 'typeMapData', './builtin-map.js', sourceHash)],
    ];
    if (check) {
        console.log('Checking both generated TypeScript modules...');
        for (const [path, expected] of targets) {
            if ((await readFile(new URL(path, import.meta.url), 'utf8')).replaceAll('\r\n', '\n') !== expected)
                throw Error(`Generated map is stale: ${path}; run node tools/build-builtin-map.mjs`);
        }
    } else {
        await mkdir(new URL('../src/hy/builtin/', import.meta.url), {recursive: true});
        for (const [path, content] of targets) await writeFile(new URL(path, import.meta.url), content);
    }
    console.log(`${check ? 'Checked' : 'Generated'} main ${main.tiles.length} tiles/${main.names.length} names; TT ${type.tiles.length} tiles/${type.names.length} names`);
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url)
    await generateBuiltinMaps({check: process.argv.includes('--check')});
